import { readFile, writeFile } from "node:fs/promises";
import { fileURLToPath } from "node:url";
import openapiTS, { astToString } from "openapi-typescript";
import { format, resolveConfig } from "prettier";
import { parse } from "yaml";

const contract = new URL("../../../celmento-spex/contracts/api.openapi.yaml", import.meta.url);
const outputDirectory = new URL("../src/lib/api/", import.meta.url);
const header = "// Generated by pnpm api:types.";

const document = parse(await readFile(contract, "utf8"));
const errorCodes = document?.components?.schemas?.ErrorCode?.enum;
if (!Array.isArray(errorCodes) || !errorCodes.every((code) => typeof code === "string")) {
  throw new Error("The OpenAPI contract must declare the ErrorCode string enum.");
}

const declaration = astToString(await openapiTS(document), {
  formatOptions: { removeComments: true },
});
const codes = [
  'import type { components } from "./schema";',
  'export const ERROR_CODES: readonly components["schemas"]["ErrorCode"][] = ' +
    JSON.stringify(errorCodes) +
    ";",
].join("\n");

for (const [filename, source] of [
  ["schema.d.ts", declaration],
  ["error-codes.ts", codes],
]) {
  const target = new URL(filename, outputDirectory);
  const style = await resolveConfig(fileURLToPath(target));
  await writeFile(target, await format(header + "\n" + source, { ...style, parser: "typescript" }));
}
